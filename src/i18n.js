// ─── Context ──────────────────────────────────────────────────
export const I18nContext = createContext(null)

// ─── Provider ─────────────────────────────────────────────────
export function I18nProvider({ children }) {
  const saved = localStorage.getItem('helixcrm_lang') || 'en'
  const [lang, setLangState] = useState(saved)

  const setLang = useCallback((code) => {
    setLangState(code)
    localStorage.setItem('helixcrm_lang', code)
    // RTL support
    const isRtl = LANGUAGES.find(l => l.code === code)?.rtl
    document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr')
    document.documentElement.setAttribute('lang', code)
  }, [])

  // Set initial RTL/lang on mount
  const isRtl = LANGUAGES.find(l => l.code === lang)?.rtl
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr')
    document.documentElement.setAttribute('lang', lang)
  }

  // t(key, vars?) — translate with optional interpolation
  // e.g. t('deals.count', { count: 5 }) → "5 deals"
  const t = useCallback((key, vars) => {
    const dict = translations[lang] || translations.en
    const fallback = translations.en
    let str = dict[key] ?? fallback[key] ?? key
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v)
      })
    }
    return str
  }, [lang])

  return (
    <I18nContext.Provider value={{ t, lang, setLang, LANGUAGES }}>
      {children}
    </I18nContext.Provider>
  )
}

// ─── Hook ─────────────────────────────────────────────────────
export function useTranslation() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useTranslation must be used inside <I18nProvider>')
  return ctx
}
